#!/usr/bin/env node
/**
 * smoke-kimi-cli.mjs — Kimi CLI Tool-mode smoke test.
 *
 * Verifies 2 Tools: search (network) and read-long (reads a small local file).
 * Not logged in / kimi not installed → overall SKIP. Network failure / single timeout → single SKIP.
 *
 * Usage: node scripts/smoke-kimi-cli.mjs
 */
import { execFileSync, spawnSync } from 'node:child_process';
import { mkdtempSync, writeFileSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';

let PASS = 0, FAIL = 0, SKIP = 0;
const pass = (n) => { PASS++; console.log(`✅ [${n}] PASS`); };
const fail = (n, m) => { FAIL++; console.log(`❌ [${n}] FAIL: ${m}`); };
const skip = (n, m) => { SKIP++; console.log(`ℹ️ [${n}] SKIP: ${m}`); };

function has(cmd) { return spawnSync('which', [cmd]).status === 0; }
function run(cmd, args, timeoutMs = 60_000) {
  try {
    return { ok: true, stdout: execFileSync(cmd, args,
      { encoding: 'utf8', stdio: ['ignore','pipe','pipe'], timeout: timeoutMs }) };
  } catch (e) {
    return { ok: false, stderr: e.stderr ?? String(e), stdout: e.stdout ?? '' };
  }
}

async function main() {
  console.log('== smoke-kimi-cli ==');
  const bin = has('kimi-cli') ? 'kimi-cli' : has('kimi') ? 'kimi' : null;
  if (!bin) { skip('env', 'kimi / kimi-cli not installed. `pip install kimi-cli` or `npm i -g @moonshot-ai/kimi-cli`'); process.exit(0); }
  console.log('using bin =', bin);

  // 1) search — may fail without KIMI_API_KEY or network
  console.log('\n[1] kimi search "DeepSeek Harness plugin marketplace"');
  const s = run(bin, ['search', '--query', 'DeepSeek Harness plugin marketplace',
    '--max', '3', '--freshness', 'year', '--json'], 60_000);
  if (!s.ok) skip(1, `kimi search failed (${String(s.stderr).slice(0,200)}). Probably missing KIMI_API_KEY / network.`);
  else {
    try { JSON.parse((s.stdout||'').trim().split('\n').slice(-1)[0] || '{}'); pass(1); }
    catch { fail(1, `output not JSON. first 200: ${s.stdout?.slice(0,200)}`); }
  }

  // 2) read-long — read a synthetic markdown file from /tmp, no network needed
  console.log('\n[2] kimi read mode=summary on a synthetic markdown file');
  const tmp = mkdtempSync(join(tmpdir(), 'kimi-smoke-'));
  const mdPath = join(tmp, 'sample.md');
  try {
    writeFileSync(mdPath, `# Smoke Test

This file was generated by dsh-plugin-cli-hub smoke-kimi-cli.mjs.

Section 1: apples
Apples grow on trees and come in many colors including red, green, and yellow.

Section 2: bananas
Bananas are yellow curved fruits that grow in bunches; they are high in potassium.

Section 3: conclusion
This file contains three fruits sections for summarization testing.
`);
    const r = run(bin, ['read', '--file', mdPath, '--mode', 'summary',
      '--detail', 'brief', '--json'], 120_000);
    if (!r.ok) skip(2, `kimi read failed (${String(r.stderr).slice(0,200)}).`);
    else {
      try { JSON.parse((r.stdout||'').trim().split('\n').slice(-1)[0] || '{}'); pass(2); }
      catch { fail(2, `output not JSON. first 200: ${r.stdout?.slice(0,200)}`); }
    }
  } finally {
    rmSync(tmp, { recursive: true, force: true });
  }

  console.log(`\n== summary: PASS=${PASS} FAIL=${FAIL} SKIP=${SKIP} ==`);
  process.exit(FAIL > 0 ? 1 : 0);
}

main().catch(e => { console.error('UNEXPECTED ERROR:', e); process.exit(2); });
